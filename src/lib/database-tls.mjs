export function databaseConnection() {
  const raw = process.env.DATABASE_URL;
  if (!raw) throw new Error("DATABASE_URL is not configured.");
  const url = new URL(raw);
  const isSupabase = url.hostname.endsWith(".supabase.com") || url.hostname.endsWith(".supabase.co");
  if (!isSupabase) return { connectionString: raw };
  for (const key of ["sslmode", "sslcert", "sslkey", "sslrootcert"]) url.searchParams.delete(key);
  // Cloudflare's `cloudflare:sockets` TLS implementation does not accept
  // Node-only `ca` options. Keep strict CA verification for local Node tools,
  // while using the Supabase pooler mode that is known to work from Workers.
  const isWorker = globalThis.navigator?.userAgent === "Cloudflare-Workers";
  const isSupabaseTransactionPooler = url.hostname.endsWith(".pooler.supabase.com") && url.port === "6543";
  return isWorker
    ? { connectionString: url.toString(), ssl: isSupabaseTransactionPooler ? false : true }
    : { connectionString: url.toString(), ssl: { rejectUnauthorized: true, ca: process.env.DATABASE_CA_CERT?.replace(/\\n/g, "\n") || SUPABASE_CA } };
}
